CREATE TABLE video_scripts (
    id                  VARCHAR(36)  NOT NULL,
    organization_id     VARCHAR(36)  NOT NULL,
    name                VARCHAR(160) NOT NULL,
    source_type         VARCHAR(32)  NOT NULL,
    source_file_name    VARCHAR(255) NULL,
    source_file_path    VARCHAR(700) NULL,
    source_content_type VARCHAR(120) NULL,
    source_size_bytes   BIGINT       NULL,
    target_market       VARCHAR(80)  NULL,
    requirements        TEXT         NULL,
    status              VARCHAR(32)  NOT NULL,
    progress            INT          NOT NULL DEFAULT 0,
    summary             TEXT         NULL,
    visual_tone         TEXT         NULL,
    script_json         LONGTEXT     NULL,
    model_config_id     VARCHAR(36)  NULL,
    model_id            VARCHAR(160) NULL,
    error_message       TEXT         NULL,
    created_by          VARCHAR(36)  NOT NULL,
    version             INT          NOT NULL DEFAULT 1,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    completed_at        TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    INDEX idx_video_scripts_org_updated (organization_id, updated_at),
    INDEX idx_video_scripts_org_status (organization_id, status),
    CONSTRAINT fk_video_scripts_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_video_scripts_user FOREIGN KEY (created_by) REFERENCES app_users(id)
);

CREATE TABLE video_script_shots (
    id                  VARCHAR(36)   NOT NULL,
    organization_id     VARCHAR(36)   NOT NULL,
    script_id           VARCHAR(36)   NOT NULL,
    sequence_no         INT           NOT NULL,
    stage               VARCHAR(40)   NOT NULL,
    title               VARCHAR(160)  NOT NULL,
    start_second        DECIMAL(10,3) NULL,
    end_second          DECIMAL(10,3) NULL,
    duration_seconds    DECIMAL(10,3) NULL,
    scene_description   TEXT          NOT NULL,
    narration           TEXT          NULL,
    shot_size           VARCHAR(80)   NULL,
    camera_movement     VARCHAR(120)  NULL,
    emotion             VARCHAR(120)  NULL,
    image_prompt_json   LONGTEXT      NULL,
    created_at          TIMESTAMP(6)  NOT NULL,
    updated_at          TIMESTAMP(6)  NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_video_script_shot_sequence (script_id, sequence_no),
    INDEX idx_video_script_shots_org_script (organization_id, script_id),
    CONSTRAINT fk_video_script_shots_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_video_script_shots_script FOREIGN KEY (script_id) REFERENCES video_scripts(id) ON DELETE CASCADE
);
